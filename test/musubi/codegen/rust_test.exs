  describe "render/1 — bundle invariants" do
    setup do
      {:ok, rendered: Rust.render(Enum.map(all_probes(), &entry/1))}
    end

    test "input order doesn't affect output", %{rendered: rendered} do
      reversed = all_probes() |> Enum.reverse() |> Enum.map(&entry/1) |> Rust.render()

      assert reversed == rendered
    end

    test "duplicate entries for one module render once", %{rendered: rendered} do
      duplicated = Rust.render(Enum.map(all_probes() ++ all_probes(), &entry/1))

      assert duplicated == rendered
    end

    test "the only `use`s are the prelude re-export and the nav module", %{rendered: rendered} do
      lines = String.split(rendered, "\n")
      uses = Enum.filter(lines, &(&1 =~ "pub use "))

      refute Enum.any?(lines, &String.starts_with?(&1, "use "))
      refute Enum.any?(lines, &String.starts_with?(&1, "pub use "))
      assert Enum.count(uses, &(&1 =~ "::generated::{")) == 1
      assert Enum.all?(uses -- [hd(uses)], &(&1 =~ ~r/pub use super::.*Ext;$/))
    end

    test "no crate-absolute paths — cross-module refs are super:: chains", %{rendered: rendered} do
      refute rendered =~ "crate::"
      assert rendered =~ "super::super::super::musubi::"
    end

    test "no container renames, no strict structs, no TS-only markers", %{rendered: rendered} do
      refute rendered =~ "rename_all"
      refute rendered =~ "deny_unknown_fields"
      refute rendered =~ "serde(default)"
      refute rendered =~ "StreamField"
      refute rendered =~ "STORES"
      refute rendered =~ "__musubi_store_id__"
    end

    test "every atom-literal variant carries an explicit rename", %{rendered: rendered} do
      normalized = normalize(rendered)

      assert normalized =~ ~s|#[serde(rename = "guest")]\nGuest,|
      assert normalized =~ ~s|#[serde(rename = "member")]\nMember,|
      assert normalized =~ ~s|#[serde(rename = "paused")]\nPaused { value: i64 },|
    end
  end

