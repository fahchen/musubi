    end
  end

  defp all_probes do
    [
      TypespecProbe,
      TypespecProbeChild,
      TypespecProbeNestedState,
      TypespecProbeWithAttrs,
      TypespecProbeWithCommand,
      TypespecProbeWithEvents,
      TypespecProbeWithReply,
      TypespecProbeWithUpload
    ]
  end

  defp entry(module) do
    data = Manifest.collect(module.__env__())
    {data.module, Map.take(data, [:kind, :fields, :commands, :events, :attrs, :uploads])}
  end

  defp empty_state,
    do: %{kind: :state, fields: [], commands: [], events: [], attrs: [], uploads: []}

  defp store_entry, do: %{empty_state() | kind: :store}

  defp state_entry(field_name, type_ast),
    do: %{empty_state() | fields: [%{name: field_name, type: type_ast, opts: []}]}

  defp captures(regex, source) do
    regex
    |> Regex.scan(source, capture: :all_but_first)
    |> List.flatten()
  end

  # Strip leading whitespace from every line so assertions exercise the line
  # CONTENT (and ordering) without coupling to nesting depth.
  defp normalize(source) do
    source
    |> String.split("\n")
    |> Enum.map_join("\n", &String.trim_leading/1)
  end
end
