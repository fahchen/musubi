defmodule Musubi.Codegen.RustTest do
  use ExUnit.Case, async: true

  alias Musubi.Codegen.Manifest
  alias Musubi.Codegen.Rust
  alias Musubi.TestSupport.TypespecProbe
  alias Musubi.TestSupport.TypespecProbeChild
  alias Musubi.TestSupport.TypespecProbeNestedState
  alias Musubi.TestSupport.TypespecProbeWithAttrs
  alias Musubi.TestSupport.TypespecProbeWithCommand
  alias Musubi.TestSupport.TypespecProbeWithEvents
  alias Musubi.TestSupport.TypespecProbeWithReply
  alias Musubi.TestSupport.TypespecProbeWithUpload

  doctest Musubi.Codegen.Rust

  # The re-export list is normative: `docs/rust-codegen.md` §4.5 plus the seven
  # state-tree names `docs/rust-reactive-state.md` §4.1 adds. It is filled to
  # rustfmt's `max_width` at the one indent level the prelude item always lands
  # on, so the bundle survives `cargo fmt --check`.
  @preamble """
  // Generated by `mix compile.musubi_rust`. Do not edit by hand.
  // Include as a module file (`mod generated;`) or via `include!`.

  #![allow(clippy::all, dead_code, unused_imports)]

  // Prelude: re-exports only. The shared runtime types are owned by the
  // client crate (`:rust_codegen_runtime_path`, default `musubi_client`).
  pub mod musubi {
      pub use ::musubi_client::generated::{
          AsyncError, AsyncResult, AsyncState, Command, Event, NoReply, State, StateTree, Store,
          StoreField, StoreId, StoreState, StreamState, Subscription, UploadSlot, UploadSlotState,
      };
  }
  """

  # The probe fixtures live under `Musubi.*`, whose top-level `pub mod musubi`
  # carries the same Rust name as the prelude module. The re-export is then the
  # first item of *that* module rather than a sibling `pub mod musubi`, which
  # would be `error[E0428]`.
  @merged_preamble """
  // Generated by `mix compile.musubi_rust`. Do not edit by hand.
  // Include as a module file (`mod generated;`) or via `include!`.

  #![allow(clippy::all, dead_code, unused_imports)]

  pub mod musubi {
      // Prelude: re-exports only. The shared runtime types are owned by the
      // client crate (`:rust_codegen_runtime_path`, default `musubi_client`).
      pub use ::musubi_client::generated::{
          AsyncError, AsyncResult, AsyncState, Command, Event, NoReply, State, StateTree, Store,
          StoreField, StoreId, StoreState, StreamState, Subscription, UploadSlot, UploadSlotState,
      };
  """

  # Emitted above every generated navigation trait; spelled out once so the
  # golden bodies below stay about the accessors.
  @ext_doc """
  /// Typed navigation for the shape above: one accessor per declared field,
  /// each handing back a handle rather than a value
  /// (`docs/rust-reactive-state.md` §4.2). Reach it through `nav`.
  """

  describe "render/1 — empty" do
    test "renders the header and the re-export prelude only" do
      assert Rust.render([]) == @preamble
    end
  end

  describe "render/1 — Musubi.State entry" do
    test "emits a bare struct in the parent module with its hoisted types sorted by name" do
      expected = """
      pub mod test_support {
      #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
      pub struct TypespecProbeNestedState {
      pub r#type: TypespecProbeNestedStateType,
      pub shipping: TypespecProbeNestedStateShipping,
      }

      #{@ext_doc}pub trait TypespecProbeNestedStateExt {
      fn r#type(&self) -> super::super::musubi::State<TypespecProbeNestedStateType>;
      fn shipping(&self) -> super::super::musubi::State<TypespecProbeNestedStateShipping>;
      }

      impl TypespecProbeNestedStateExt for super::super::musubi::State<TypespecProbeNestedState> {
      fn r#type(&self) -> super::super::musubi::State<TypespecProbeNestedStateType> {
      self.child("type")
      }
      fn shipping(&self) -> super::super::musubi::State<TypespecProbeNestedStateShipping> {
      self.child("shipping")
      }
      }

      #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
      pub struct TypespecProbeNestedStateShipping {
      pub street: String,
      pub city: String,
      }

      #{@ext_doc}pub trait TypespecProbeNestedStateShippingExt {
      fn street(&self) -> super::super::musubi::State<String>;
      fn city(&self) -> super::super::musubi::State<String>;
      }

      impl TypespecProbeNestedStateShippingExt
      for super::super::musubi::State<TypespecProbeNestedStateShipping>
      {
      fn street(&self) -> super::super::musubi::State<String> {
      self.child("street")
      }
      fn city(&self) -> super::super::musubi::State<String> {
      self.child("city")
      }
      }

      #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
      pub enum TypespecProbeNestedStateType {
      #[serde(rename = "guest")]
      Guest,
      #[serde(rename = "member")]
      Member,
      }
      }
      }

      // Navigation traits, flat. One `use <bundle>::nav::*;` per consumer file
      // brings every generated accessor into scope.
      pub mod nav {
      pub use super::musubi::test_support::TypespecProbeNestedStateExt;
      pub use super::musubi::test_support::TypespecProbeNestedStateShippingExt;
      }
      """

      rendered = Rust.render([entry(TypespecProbeNestedState)])

      assert normalize(rendered) == normalize(@merged_preamble <> "\n" <> expected)
    end
  end

  describe "render/1 — nested state modules" do
