  end

  describe "render/1 — Musubi.Store entry" do
    test "a store is a module of its own carrying the marker, the impl and State" do
      expected = """
      pub mod test_support {
      pub mod typespec_probe_child {
      /// Zero-sized marker type implementing `Store`. Distinct from `State`.
      pub struct TypespecProbeChild;

      impl super::super::super::musubi::Store for TypespecProbeChild {
      const MODULE: &'static str = "Musubi.TestSupport.TypespecProbeChild";
      type State = State;
      type Params = Params;
      }

      /// The store's rendered shape: state fields plus one `UploadSlot` per
      /// declared upload. Reached as `<TypespecProbeChild as Store>::State`.
      #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
      pub struct State {
      pub amount: i64,
      }

      #{@ext_doc}pub trait TypespecProbeChildExt {
      fn amount(&self) -> super::super::super::musubi::State<i64>;
      }

      impl TypespecProbeChildExt for super::super::super::musubi::State<State> {
      fn amount(&self) -> super::super::super::musubi::State<i64> {
      self.child("amount")
      }
      }

      impl TypespecProbeChildExt for super::super::super::musubi::StoreState<State> {
      fn amount(&self) -> super::super::super::musubi::State<i64> {
      TypespecProbeChildExt::amount(&self.fields())
      }
      }

      /// The mount params object, one field per `attr/3` declaration: required
      /// attrs are plain fields, optional ones `Option` that serialize to an
      /// absent key rather than an explicit `null`. A store declaring no `attr`
      /// gets an empty struct, which serializes to `{}`.
      #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
      pub struct Params {}
      }
      }
      }

      // Navigation traits, flat. One `use <bundle>::nav::*;` per consumer file
      // brings every generated accessor into scope.
      pub mod nav {
      pub use super::musubi::test_support::typespec_probe_child::TypespecProbeChildExt;
      }
      """

      rendered = Rust.render([entry(TypespecProbeChild)])

      assert normalize(rendered) == normalize(@merged_preamble <> "\n" <> expected)
    end

    test "streams, async values and child stores project onto the runtime types" do
      rendered = Rust.render([entry(TypespecProbe), entry(TypespecProbeChild)])
      prelude = "super::super::super::musubi"
      child = "super::super::super::musubi::test_support::typespec_probe_child::State"

      assert rendered =~ "pub messages: Vec<String>,"

      assert normalize(rendered) =~
               normalize("""
               pub items:
                   Vec<#{child}>,
               """)

      assert rendered =~ "pub tags: Vec<String>,"

      # Past 100 columns the generic argument list is wrapped exactly the way
      # rustfmt wraps it, so the bundle survives `cargo fmt --all --check`.
      assert normalize(rendered) =~
               normalize("""
               pub load_stream: #{prelude}::AsyncResult<
                   Vec<#{child}>,
               >,
               """)

      assert normalize(rendered) =~
               normalize("""
               pub profile: #{prelude}::AsyncResult<
                   #{child},
               >,
               """)

      assert normalize(rendered) =~
               normalize("""
               pub child: #{prelude}::StoreField<
                   #{child},
               >,
               """)
    end

    test "no emitted field line exceeds rustfmt's 100-column max_width" do
      rendered = Rust.render(Enum.map(all_probes(), &entry/1))

      over_width =
        rendered
        |> String.split("\n")
        |> Enum.filter(&(String.contains?(&1, "pub ") and String.length(&1) > 100))

      assert over_width == []
    end

    # The stronger form of the assertion above: §4.1 makes the bundle
    # rustfmt-stable by construction, so a consumer running `cargo fmt --check`
    # over it must see no diff. Skipped where rustfmt is not installed — CI's
    # `cargo fmt --all --check` job covers the crates, this covers the bundle.
    test "the rendered bundle survives `rustfmt --check` unchanged" do
      rustfmt = System.find_executable("rustfmt")

      path =
        Path.join(
          System.tmp_dir!(),
          "musubi_rust_bundle_#{System.unique_integer([:positive])}.rs"
        )

      if rustfmt do
        on_exit(fn -> File.rm(path) end)
        File.write!(path, Rust.render(Enum.map(all_probes(), &entry/1)))

        assert {_output, 0} =
                 System.cmd(rustfmt, ["--edition", "2024", "--check", path],
                   stderr_to_stdout: true
                 )
      end
    end

    test "`Module.t()` on a store points at its `State`, never at the marker" do
      rendered = Rust.render([entry(TypespecProbe), entry(TypespecProbeChild)])

      refute rendered =~ "musubi::test_support::TypespecProbeChild"
    end

    test "a union of maps sharing a distinct-atom key hoists an internally tagged enum" do
      rendered = Rust.render([entry(TypespecProbe)])

      assert rendered =~ "pub status: TypespecProbeStatus,"

      assert normalize(rendered) =~
               normalize("""
               #[derive(Debug, Clone, PartialEq, serde::Serialize, serde::Deserialize)]
               #[serde(tag = "type")]
               pub enum TypespecProbeStatus {
                   #[serde(rename = "active")]
                   Active,
                   #[serde(rename = "paused")]
                   Paused { value: i64 },
               }
               """)
    end
  end

  # The navigation column of `docs/rust-reactive-state.md` §4.3: the snapshot
  # struct is unchanged, and every field also gets an accessor whose return
  # type is fixed by the field's manifest type.
  describe "render/1 — navigation surface" do
    setup do
      {:ok, rendered: normalize(Rust.render([entry(TypespecProbe), entry(TypespecProbeChild)]))}
    end

    test "a stream is keyed, a list is indexed", %{rendered: rendered} do
      child = "super::super::super::musubi::test_support::typespec_probe_child::State"

      assert rendered =~ "fn messages(&self) -> super::super::super::musubi::StreamState<String>;"
      assert rendered =~ "fn tags(&self) -> super::super::super::musubi::State<Vec<String>>;"

      assert rendered =~
               normalize("""
               fn items(
                   &self,
               ) -> super::super::super::musubi::StreamState<
                   #{child},
               >;
               """)
    end

    test "a child store navigates as StoreState, an async node as AsyncState", %{
      rendered: rendered
    } do
      child = "super::super::super::musubi::test_support::typespec_probe_child::State"

      assert rendered =~
               normalize("""
               fn child(
                   &self,
               ) -> super::super::super::musubi::StoreState<
                   #{child},
               >;
               """)

      assert rendered =~
               normalize("""
               fn profile(
                   &self,
               ) -> super::super::super::musubi::AsyncState<
                   #{child},
               >;
               """)

      # `stream_async`: the result is a stream, so the handle is
      # `AsyncState<Vec<T>>` — the shape `ok_stream()` is defined on.
      assert rendered =~
               normalize("""
               fn load_stream(
                   &self,
               ) -> super::super::super::musubi::AsyncState<
                   Vec<#{child}>,
               >;
               """)
    end

    test "a union is a leaf: the hoisted enum navigates as State<E>, with no Ext", %{
      rendered: rendered
    } do
      assert rendered =~
               "fn status(&self) -> super::super::super::musubi::State<TypespecProbeStatus>;"

      refute rendered =~ "TypespecProbeStatusExt"
    end

    test "a store shape carries two impls, the second forwarding through fields()", %{
      rendered: rendered
    } do
      assert rendered =~
               normalize("""
               impl TypespecProbeChildExt for super::super::super::musubi::State<State> {
                   fn amount(&self) -> super::super::super::musubi::State<i64> {
                       self.child("amount")
                   }
               }
               """)

      assert rendered =~
               normalize("""
               impl TypespecProbeChildExt for super::super::super::musubi::StoreState<State> {
                   fn amount(&self) -> super::super::super::musubi::State<i64> {
                       TypespecProbeChildExt::amount(&self.fields())
                   }
               }
               """)
    end

    test "an upload slot navigates to UploadSlotState" do
      rendered = normalize(Rust.render([entry(TypespecProbeWithUpload)]))

      assert rendered =~ "fn avatar(&self) -> super::super::super::musubi::UploadSlotState;"

      assert rendered =~
               normalize("""
               fn cover(&self) -> super::super::super::musubi::UploadSlotState {
                   self.child("cover").into()
               }
               """)
    end

    test "an accessor addresses the wire key, not the escaped ident" do
      rendered = normalize(Rust.render([entry(TypespecProbeNestedState)]))

      assert rendered =~
               normalize("""
               fn r#type(&self) -> super::super::musubi::State<TypespecProbeNestedStateType> {
                   self.child("type")
               }
               """)
    end

    test "shapes that never reach the state tree get no navigation" do
      rendered = Rust.render([entry(TypespecProbeWithAttrs), entry(TypespecProbeWithReply)])

      # A struct hoisted out of an `attr` (mount params) and a command reply
      # are not nodes of any tree.
      assert rendered =~ "pub struct TypespecProbeWithAttrsParamsFilter {"
      refute rendered =~ "TypespecProbeWithAttrsParamsFilterExt"
      refute rendered =~ "PayReplyExt"
      refute rendered =~ "ParamsExt"
    end

    test "the nav module is the last top-level item and lists every trait" do
      rendered = Rust.render(Enum.map(all_probes(), &entry/1))

      traits = captures(~r/pub trait (\w+) \{/, rendered)
      exported = captures(~r/pub use super::[\w:]*?(\w+);/, rendered)

      assert Enum.sort(traits) == Enum.sort(exported)

      [_bundle, tail] = String.split(rendered, "pub mod nav {\n")
      lines = String.split(tail, "\n", trim: true)

      assert Enum.all?(lines, &(String.starts_with?(&1, "    pub use super::") or &1 == "}"))
    end

    test "a top-level module colliding with the nav module raises" do
      assert_raise ArgumentError, ~r/navigation re-export module/, fn ->
        Rust.render([{Nav.CartStore, store_entry()}])
      end
    end

    test "a prelude configured as `nav` raises" do
      assert_raise ArgumentError, ~r/navigation re-export module/, fn ->
        Rust.render([], root_module: "nav")
      end
    end
  end

